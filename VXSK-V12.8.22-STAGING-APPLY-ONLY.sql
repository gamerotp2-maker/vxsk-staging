CREATE OR REPLACE FUNCTION public.vxsk_social_find_v2(p_term text)
RETURNS TABLE(user_id uuid,nickname text,avatar_path text)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO '' AS $$
 SELECT p.user_id,p.nickname,
 CASE WHEN (u.raw_user_meta_data->>'avatar_path') LIKE p.user_id::text || '/%'
  THEN u.raw_user_meta_data->>'avatar_path' ELSE NULL END
 FROM public.vxsk_social_profiles p JOIN auth.users u ON u.id=p.user_id
 WHERE auth.uid() IS NOT NULL AND u.email_confirmed_at IS NOT NULL AND p.user_id<>auth.uid()
 AND char_length(btrim(coalesce(p_term,''))) BETWEEN 2 AND 30
 AND position(lower(btrim(p_term)) IN lower(p.nickname))>0
 AND NOT EXISTS(SELECT 1 FROM public.vxsk_social_blocks b WHERE
  (b.blocker=auth.uid() AND b.blocked=p.user_id) OR (b.blocker=p.user_id AND b.blocked=auth.uid()))
 ORDER BY lower(p.nickname) LIMIT 20;
$$;
CREATE OR REPLACE FUNCTION public.vxsk_social_find(p_term text)
RETURNS TABLE(user_id uuid,nickname text)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO '' AS $$
 SELECT f.user_id,f.nickname FROM public.vxsk_social_find_v2(p_term) f;
$$;
CREATE OR REPLACE FUNCTION public.vxsk_social_request(p_peer uuid)
RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER SET search_path TO '' AS $$
DECLARE uid uuid := auth.uid();
BEGIN
 IF uid IS NULL OR p_peer IS NULL OR uid=p_peer THEN RETURN false; END IF;
 IF NOT EXISTS(SELECT 1 FROM public.vxsk_social_profiles WHERE user_id=uid) OR
  NOT EXISTS(SELECT 1 FROM public.vxsk_social_profiles p JOIN auth.users u ON u.id=p.user_id
   WHERE p.user_id=p_peer AND u.email_confirmed_at IS NOT NULL) THEN RETURN false; END IF;
 IF EXISTS(SELECT 1 FROM public.vxsk_social_blocks b WHERE
  (b.blocker=uid AND b.blocked=p_peer) OR (b.blocker=p_peer AND b.blocked=uid)) THEN RETURN false; END IF;
 IF (SELECT count(*) FROM public.vxsk_social_links WHERE requested_by=uid AND created_at>now()-interval '1 day') >= 20 THEN RETURN false; END IF;
 INSERT INTO public.vxsk_social_links(user_low,user_high,requested_by,status)
 VALUES(least(uid,p_peer),greatest(uid,p_peer),uid,'pending') ON CONFLICT DO NOTHING;
 RETURN found;
END;
$$;
-- New showmatch invitations: players choose an accepted friend; no staff-created fake opponents.
CREATE TABLE IF NOT EXISTS public.vxsk_showmatch_challenges (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 challenger uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
 opponent uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
 game text NOT NULL CHECK(game IN ('Rocket League','VALORANT','League of Legends')),
 mode text NOT NULL CHECK(char_length(btrim(mode)) BETWEEN 2 AND 40),
 state text NOT NULL DEFAULT 'pending' CHECK(state IN ('pending','accepted','declined','cancelled','scheduled','completed')),
 created_at timestamptz NOT NULL DEFAULT now(),updated_at timestamptz NOT NULL DEFAULT now(),
 CHECK(challenger<>opponent)
);
CREATE INDEX IF NOT EXISTS vxsk_showmatch_by_challenger ON public.vxsk_showmatch_challenges(challenger,created_at DESC);
CREATE INDEX IF NOT EXISTS vxsk_showmatch_by_opponent ON public.vxsk_showmatch_challenges(opponent,created_at DESC);
ALTER TABLE public.vxsk_showmatch_challenges ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.vxsk_showmatch_challenges FROM PUBLIC,anon,authenticated;
CREATE OR REPLACE FUNCTION public.vxsk_showmatch_invite(p_peer uuid,p_game text,p_mode text)
RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER SET search_path TO '' AS $$
DECLARE uid uuid:=auth.uid();
BEGIN
 IF uid IS NULL OR p_peer IS NULL OR p_peer=uid OR p_game NOT IN ('Rocket League','VALORANT','League of Legends')
  OR char_length(btrim(coalesce(p_mode,''))) NOT BETWEEN 2 AND 40 THEN RETURN false; END IF;
 IF NOT EXISTS(SELECT 1 FROM public.vxsk_social_links l WHERE l.user_low=least(uid,p_peer)
  AND l.user_high=greatest(uid,p_peer) AND l.status='accepted') THEN RETURN false; END IF;
 IF EXISTS(SELECT 1 FROM public.vxsk_social_blocks b WHERE (b.blocker=uid AND b.blocked=p_peer)
  OR (b.blocker=p_peer AND b.blocked=uid)) THEN RETURN false; END IF;
 IF (SELECT count(*) FROM public.vxsk_showmatch_challenges WHERE challenger=uid AND created_at>now()-interval '1 day')>=8 THEN RETURN false; END IF;
 IF EXISTS(SELECT 1 FROM public.vxsk_showmatch_challenges WHERE challenger=uid AND opponent=p_peer AND state='pending') THEN RETURN false; END IF;
 INSERT INTO public.vxsk_showmatch_challenges(challenger,opponent,game,mode) VALUES(uid,p_peer,p_game,btrim(p_mode));
 RETURN true;
END;
$$;
CREATE OR REPLACE FUNCTION public.vxsk_showmatch_answer(p_challenge uuid,p_accept boolean)
RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER SET search_path TO '' AS $$
BEGIN
