 ORDER BY c.updated_at DESC LIMIT 100;
$$;
CREATE OR REPLACE FUNCTION public.vxsk_showmatch_staff_status(p_challenge uuid,p_state text)
RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER SET search_path TO '' AS $$
