-- Users keep their account nickname; a safe autogenerated fallback handles invalid/missing/colliding names.
CREATE OR REPLACE FUNCTION public.vxsk_social_sync_auth_profile()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path TO '' AS $$
DECLARE preferred text; fallback text;
BEGIN
 IF NEW.email_confirmed_at IS NULL THEN RETURN NEW; END IF;
 preferred := btrim(coalesce(NEW.raw_user_meta_data->>'vxsk_nickname',''));
 IF preferred !~ '^[A-Za-z0-9_.-]{3,24}$'
 OR lower(preferred) IN ('owner','admin','moderator','vxsk','vxskstaff','support','official') THEN
   preferred := 'Player_'||left(replace(NEW.id::text,'-',''),12);
 END IF;
 fallback := 'Player_'||replace(NEW.id::text,'-',''); fallback := left(fallback,24);
 BEGIN
  INSERT INTO public.vxsk_social_profiles(user_id,nickname,discoverable,share_avatar)
  VALUES(NEW.id,preferred,true,true)
  ON CONFLICT (user_id) DO UPDATE SET nickname=excluded.nickname,discoverable=true,share_avatar=true,updated_at=now();
 EXCEPTION WHEN unique_violation THEN
  INSERT INTO public.vxsk_social_profiles(user_id,nickname,discoverable,share_avatar)
  VALUES(NEW.id,fallback,true,true)
  ON CONFLICT (user_id) DO UPDATE SET nickname=excluded.nickname,discoverable=true,share_avatar=true,updated_at=now();
 END;
 RETURN NEW;
END;
$$;
