END;
$$;
CREATE OR REPLACE FUNCTION public.vxsk_showmatch_mine()
RETURNS TABLE(id uuid,game text,mode text,state text,created_at timestamptz,peer_name text,incoming boolean)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO '' AS $$
 SELECT c.id,c.game,c.mode,c.state,c.created_at,
 coalesce(p.nickname,'VXSK PLAYER'),c.opponent=auth.uid()
 FROM public.vxsk_showmatch_challenges c
 LEFT JOIN public.vxsk_social_profiles p ON p.user_id=CASE WHEN c.opponent=auth.uid() THEN c.challenger ELSE c.opponent END
 WHERE auth.uid() IS NOT NULL AND (c.challenger=auth.uid() OR c.opponent=auth.uid())
 ORDER BY c.created_at DESC LIMIT 80;
$$;
CREATE OR REPLACE FUNCTION public.vxsk_showmatch_staff_queue()
RETURNS TABLE(id uuid,game text,mode text,state text,challenger_name text,opponent_name text,created_at timestamptz)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO '' AS $$
