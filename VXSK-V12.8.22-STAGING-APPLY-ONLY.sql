 UPDATE public.vxsk_showmatch_challenges SET state=CASE WHEN p_accept THEN 'accepted' ELSE 'declined' END,updated_at=now()
 WHERE id=p_challenge AND opponent=auth.uid() AND state='pending';RETURN found;
END;
$$;
CREATE OR REPLACE FUNCTION public.vxsk_showmatch_cancel(p_challenge uuid)
