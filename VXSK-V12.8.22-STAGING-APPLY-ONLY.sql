CREATE OR REPLACE FUNCTION public.vxsk_group_call_join(p_group uuid)
RETURNS uuid LANGUAGE plpgsql SECURITY DEFINER SET search_path TO '' AS $$
DECLARE uid uuid:=auth.uid(); sid uuid:=gen_random_uuid();
BEGIN
 IF uid IS NULL OR p_group IS NULL OR NOT EXISTS(SELECT 1 FROM public.vxsk_group_members m
  WHERE m.group_id=p_group AND m.user_id=uid AND m.status='active') THEN RETURN NULL; END IF;
 PERFORM pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtext('vxsk-group-call:'||p_group::text));
 IF (SELECT count(*) FROM public.vxsk_group_call_presence p WHERE p.group_id=p_group
  AND p.user_id<>uid AND p.last_seen>now()-interval '75 seconds')>=4 THEN RETURN NULL; END IF;
 IF EXISTS(SELECT 1 FROM public.vxsk_group_call_presence p JOIN public.vxsk_social_blocks b
  ON ((b.blocker=uid AND b.blocked=p.user_id) OR (b.blocker=p.user_id AND b.blocked=uid))
  WHERE p.group_id=p_group AND p.last_seen>now()-interval '75 seconds') THEN RETURN NULL; END IF;
 INSERT INTO public.vxsk_group_call_presence(group_id,user_id,session_id,last_seen)
 VALUES(p_group,uid,sid,now())
 ON CONFLICT(group_id,user_id) DO UPDATE SET session_id=excluded.session_id,last_seen=now();
 DELETE FROM public.vxsk_group_call_signals WHERE created_at<now()-interval '1 day';
 RETURN sid;
END;
$$;
CREATE OR REPLACE FUNCTION public.vxsk_group_call_heartbeat(p_group uuid,p_session uuid)
RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER SET search_path TO '' AS $$
BEGIN
 UPDATE public.vxsk_group_call_presence p SET last_seen=now()
 WHERE p.group_id=p_group AND p.user_id=auth.uid() AND p.session_id=p_session
 AND EXISTS(SELECT 1 FROM public.vxsk_group_members m WHERE m.group_id=p_group AND m.user_id=auth.uid() AND m.status='active');
 RETURN found;
END;
$$;
CREATE OR REPLACE FUNCTION public.vxsk_group_call_roster(p_group uuid)
RETURNS TABLE(user_id uuid,session_id uuid,nickname text)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO '' AS $$
 SELECT p.user_id,p.session_id,coalesce(n.nickname,'VXSK PLAYER')
 FROM public.vxsk_group_call_presence p
 JOIN public.vxsk_group_members m ON m.group_id=p.group_id AND m.user_id=p.user_id AND m.status='active'
 LEFT JOIN public.vxsk_social_profiles n ON n.user_id=p.user_id
 WHERE auth.uid() IS NOT NULL AND p.group_id=p_group AND p.last_seen>now()-interval '75 seconds'
 AND EXISTS(SELECT 1 FROM public.vxsk_group_members me WHERE me.group_id=p_group AND me.user_id=auth.uid() AND me.status='active')
 AND NOT EXISTS(SELECT 1 FROM public.vxsk_social_blocks b WHERE
  (b.blocker=auth.uid() AND b.blocked=p.user_id) OR (b.blocker=p.user_id AND b.blocked=auth.uid()))
 ORDER BY lower(coalesce(n.nickname,'VXSK PLAYER')) LIMIT 4;
$$;
CREATE OR REPLACE FUNCTION public.vxsk_group_call_signal(p_group uuid,p_session uuid,p_peer uuid,p_kind text,p_body jsonb)
RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER SET search_path TO '' AS $$
DECLARE uid uuid:=auth.uid(); target uuid;
BEGIN
 IF uid IS NULL OR p_group IS NULL OR p_peer IS NULL OR p_peer=uid
  OR p_kind NOT IN('offer','answer','ice') OR p_body IS NULL OR jsonb_typeof(p_body)<>'object'
  OR pg_catalog.octet_length(p_body::text)>16000 THEN RETURN false; END IF;
 IF NOT EXISTS(SELECT 1 FROM public.vxsk_group_call_presence p WHERE p.group_id=p_group AND p.user_id=uid
  AND p.session_id=p_session AND p.last_seen>now()-interval '75 seconds') THEN RETURN false; END IF;
 IF NOT EXISTS(SELECT 1 FROM public.vxsk_group_members WHERE group_id=p_group AND user_id=uid AND status='active') THEN RETURN false; END IF;
 IF EXISTS(SELECT 1 FROM public.vxsk_social_blocks b WHERE (b.blocker=uid AND b.blocked=p_peer)
  OR (b.blocker=p_peer AND b.blocked=uid)) THEN RETURN false; END IF;
 SELECT p.session_id INTO target FROM public.vxsk_group_call_presence p JOIN public.vxsk_group_members m
  ON m.group_id=p.group_id AND m.user_id=p.user_id AND m.status='active'
 WHERE p.group_id=p_group AND p.user_id=p_peer AND p.last_seen>now()-interval '75 seconds';
 IF target IS NULL THEN RETURN false; END IF;
 IF (SELECT count(*) FROM public.vxsk_group_call_signals WHERE group_id=p_group AND sender_id=uid
  AND created_at>now()-interval '5 minutes')>=600 THEN RETURN false; END IF;
 INSERT INTO public.vxsk_group_call_signals(group_id,sender_id,sender_session,recipient_id,recipient_session,kind,body)
 VALUES(p_group,uid,p_session,p_peer,target,p_kind,p_body);
 RETURN true;
END;
$$;
CREATE OR REPLACE FUNCTION public.vxsk_group_call_events(p_group uuid,p_session uuid,p_after bigint DEFAULT 0)
RETURNS jsonb LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO '' AS $$
 SELECT coalesce(jsonb_agg(jsonb_build_object('id',s.id,'sender',s.sender_id,'sender_session',s.sender_session,
  'kind',s.kind,'body',s.body) ORDER BY s.id),'[]'::jsonb)
 FROM (SELECT s.* FROM public.vxsk_group_call_signals s
  JOIN public.vxsk_group_call_presence sender ON sender.group_id=s.group_id AND sender.user_id=s.sender_id
    AND sender.session_id=s.sender_session AND sender.last_seen>now()-interval '75 seconds'
 WHERE auth.uid() IS NOT NULL AND s.group_id=p_group AND s.recipient_id=auth.uid()
  AND s.recipient_session=p_session AND s.id>greatest(coalesce(p_after,0),0)
  AND EXISTS(SELECT 1 FROM public.vxsk_group_call_presence mine WHERE mine.group_id=p_group AND mine.user_id=auth.uid()
    AND mine.session_id=p_session AND mine.last_seen>now()-interval '75 seconds')
  AND NOT EXISTS(SELECT 1 FROM public.vxsk_social_blocks b WHERE
     (b.blocker=auth.uid() AND b.blocked=s.sender_id) OR (b.blocker=s.sender_id AND b.blocked=auth.uid()))
 ORDER BY s.id LIMIT 100) s;
$$;
CREATE OR REPLACE FUNCTION public.vxsk_group_call_leave(p_group uuid,p_session uuid)
RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER SET search_path TO '' AS $$
BEGIN
 DELETE FROM public.vxsk_group_call_presence WHERE group_id=p_group AND user_id=auth.uid() AND session_id=p_session;
 RETURN found;
END;
$$;
