-- Consent-based private group voice/video calls, maximum 4 active participants.
-- Membership checked server-side; no direct SELECT to any call/signaling table.
CREATE TABLE IF NOT EXISTS public.vxsk_group_call_presence (
 group_id uuid NOT NULL,
 user_id uuid NOT NULL,
 session_id uuid NOT NULL DEFAULT gen_random_uuid(),
 last_seen timestamptz NOT NULL DEFAULT now(),
 PRIMARY KEY(group_id,user_id),
 FOREIGN KEY(group_id,user_id) REFERENCES public.vxsk_group_members(group_id,user_id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS public.vxsk_group_call_signals (
 id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 group_id uuid NOT NULL REFERENCES public.vxsk_group_rooms(id) ON DELETE CASCADE,
 sender_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
 sender_session uuid NOT NULL,
 recipient_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
 recipient_session uuid NOT NULL,
 kind text NOT NULL CHECK(kind IN ('offer','answer','ice')),
 body jsonb NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now(),
 CHECK(sender_id<>recipient_id)
);
CREATE INDEX IF NOT EXISTS vxsk_group_call_signals_recipient ON public.vxsk_group_call_signals(group_id,recipient_id,recipient_session,id);
ALTER TABLE public.vxsk_group_call_presence ENABLE ROW LEVEL SECURITY;
