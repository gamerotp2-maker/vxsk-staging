  END IF;
  fallback := left('Player_'||replace(u.id::text,'-',''),24);
  BEGIN
   INSERT INTO public.vxsk_social_profiles(user_id,nickname,discoverable,share_avatar)
   VALUES(u.id,preferred,true,true)
   ON CONFLICT (user_id) DO UPDATE SET nickname=excluded.nickname,discoverable=true,share_avatar=true,updated_at=now();
  EXCEPTION WHEN unique_violation THEN
   INSERT INTO public.vxsk_social_profiles(user_id,nickname,discoverable,share_avatar)
   VALUES(u.id,fallback,true,true)
   ON CONFLICT (user_id) DO UPDATE SET nickname=excluded.nickname,discoverable=true,share_avatar=true,updated_at=now();
  END;
 END LOOP;
END;
