-- VXSK V12.8.32 — TARGET PROJECT: opzqnmahfgehaewgciwg (CURRENT GITHUB PAGES DATABASE)
-- Install ONLY there, not former Netlify/production project ziaihifbmmrvngorarfb.
-- Run after existing Hub, Community, Content Editor and Owner Staff Manager migrations.
-- Does NOT delete existing users, staff roles, messages, friendships or old covers.
-- New event posters are public; private avatars stay private and permission checked.
BEGIN;

-- The original Hub schema may not contain prize even though a staff form uses it.
ALTER TABLE public.vxsk_hub_events ADD COLUMN IF NOT EXISTS prize text;
ALTER TABLE public.match_center_posts ADD COLUMN IF NOT EXISTS cover_path text;
ALTER TABLE public.vxsk_hub_events ADD COLUMN IF NOT EXISTS cover_path text;
ALTER TABLE public.vxsk_hub_matches ADD COLUMN IF NOT EXISTS cover_path text;

-- Only simple Storage object paths generated by the VXSK uploader may be saved.
DO $plpgsql$
DECLARE v_table text;
BEGIN
  FOREACH v_table IN ARRAY ARRAY['match_center_posts','vxsk_hub_events','vxsk_hub_matches'] LOOP
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid=('public.'||v_table)::regclass AND conname=v_table||'_cover_path_12832_check') THEN
      EXECUTE format('ALTER TABLE public.%I ADD CONSTRAINT %I CHECK (cover_path IS NULL OR cover_path ~ %L)',
          v_table,v_table||'_cover_path_12832_check','^[0-9a-f-]{36}/[0-9a-f-]{36}\.webp$');
    END IF;
  END LOOP;
END $plpgsql$;

-- Existing RLS still controls these writes. Only add missing column privileges.
GRANT SELECT (cover_path) ON public.match_center_posts TO anon,authenticated;
GRANT INSERT (cover_path), UPDATE (cover_path) ON public.match_center_posts TO authenticated;
GRANT SELECT (cover_path, prize) ON public.vxsk_hub_events TO anon,authenticated;
GRANT INSERT (cover_path, prize), UPDATE (cover_path, prize) ON public.vxsk_hub_events TO authenticated;
GRANT SELECT (cover_path) ON public.vxsk_hub_matches TO anon,authenticated;
GRANT INSERT (cover_path), UPDATE (cover_path) ON public.vxsk_hub_matches TO authenticated;

-- IMPORTANT: Create bucket `vxsk-event-covers` manually in Storage Dashboard:
-- PUBLIC access; max file size 2 MB; allowed MIME: image/webp.
-- Never make `vxsk-avatars` public. Policies below are scoped to event posters.
-- This SQL intentionally does not modify Storage bucket metadata directly.

-- Storage writes: authorized authenticated editor, MFA AAL2, own UUID folder only.
-- Read access to POSTERS is public via public bucket URL; this never alters private avatar bucket.
DO $plpgsql$
BEGIN
 IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname='storage' AND tablename='objects' AND policyname='vxsk_12832_covers_insert') THEN
  CREATE POLICY vxsk_12832_covers_insert ON storage.objects FOR INSERT TO authenticated
    WITH CHECK (bucket_id='vxsk-event-covers'
      AND (storage.foldername(name))[1]=auth.uid()::text
      AND name ~ ('^'||auth.uid()::text||'/[0-9a-f-]{36}\.webp$')
      AND (auth.jwt()->>'aal')='aal2'
      AND COALESCE(public.can_edit_match_center(),false));
 END IF;
 IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname='storage' AND tablename='objects' AND policyname='vxsk_12832_covers_update') THEN
  CREATE POLICY vxsk_12832_covers_update ON storage.objects FOR UPDATE TO authenticated
    USING (bucket_id='vxsk-event-covers' AND (storage.foldername(name))[1]=auth.uid()::text
      AND (auth.jwt()->>'aal')='aal2' AND COALESCE(public.can_edit_match_center(),false))
    WITH CHECK (bucket_id='vxsk-event-covers' AND (storage.foldername(name))[1]=auth.uid()::text
      AND (auth.jwt()->>'aal')='aal2' AND COALESCE(public.can_edit_match_center(),false));
 END IF;
 IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname='storage' AND tablename='objects' AND policyname='vxsk_12832_covers_delete') THEN
  CREATE POLICY vxsk_12832_covers_delete ON storage.objects FOR DELETE TO authenticated
    USING (bucket_id='vxsk-event-covers' AND (storage.foldername(name))[1]=auth.uid()::text
      AND (auth.jwt()->>'aal')='aal2' AND COALESCE(public.can_edit_match_center(),false));
 END IF;
 -- Optional authenticated file listing (Storage SDK may use SELECT to remove a file).
 IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname='storage' AND tablename='objects' AND policyname='vxsk_12832_covers_select') THEN
  CREATE POLICY vxsk_12832_covers_select ON storage.objects FOR SELECT TO authenticated
    USING (bucket_id='vxsk-event-covers' AND (storage.foldername(name))[1]=auth.uid()::text
      AND (auth.jwt()->>'aal')='aal2' AND COALESCE(public.can_edit_match_center(),false));
 END IF;
END $plpgsql$;

-- V12.8.28 avatar SQL includes an authorization helper, but some projects
-- never installed the accompanying PRIVATE bucket SELECT policy. Fix that gap.
DO $plpgsql$
BEGIN
 IF to_regprocedure('public.vxsk_can_view_social_avatar(text)') IS NOT NULL AND
    NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname='storage' AND tablename='objects' AND policyname='vxsk_avatars_read_social_1288') THEN
   CREATE POLICY vxsk_avatars_read_social_1288 ON storage.objects FOR SELECT TO authenticated
     USING (bucket_id='vxsk-avatars'
        AND public.vxsk_can_view_social_avatar((storage.foldername(name))[1]));
 END IF;
END $plpgsql$;
COMMIT;
NOTIFY pgrst, 'reload schema';
